CREATE TABLE IF NOT EXISTS public.series_salvas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    criado_em timestamptz NOT NULL DEFAULT now(),
    tvmaze_id integer NOT NULL UNIQUE,
    nome text NOT NULL,
    ano_estreia text,
    nota numeric,
    generos text,
    poster_url text,
    dados_extra jsonb,
    assistida boolean NOT NULL DEFAULT false,
    anotacao text
);

ALTER TABLE public.series_salvas ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Permitir leitura anon" 
ON public.series_salvas FOR SELECT
TO anon
USING (true);

CREATE POLICY "Permitir insercao anon" 
ON public.series_salvas FOR INSERT
TO anon
WITH CHECK (true);

CREATE POLICY "Permitir atualizacao anon" 
ON public.series_salvas FOR UPDATE
TO anon
USING (true)
WITH CHECK (true);

CREATE POLICY "Permitir exclusao anon" 
ON public.series_salvas FOR DELETE
TO anon
USING (true);
